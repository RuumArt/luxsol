const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('www/local/templates/luxol/components/bitrix/sale.order.ajax/order/order_ajax.js','utf8');
const start=source.indexOf('getBasketItemDisplayProps: function(data)');
const end=source.indexOf('createBasketItemContent: function(data)',start);
if(start<0||end<0)throw new Error('Checkout property formatter not found');
const component=vm.runInNewContext('({'+source.slice(start,end)+'})');
let passed=0;
const check=(name,ok)=>{if(!ok)throw new Error('FAIL: '+name);passed++;console.log('PASS:',name);};
const render=(area,cuts)=>component.getBasketItemDisplayProps({PROPS:[{CODE:'SQUARE',VALUE:area},{CODE:'SIZES_STR',VALUE:cuts}]});
const area=(props)=>props.find(p=>p.CODE==='SQUARE').VALUE;
check('AJAX checkout restores 15.75 from old 15.8',area(render('15,8','3,5 × 1,5 m × 3 ks.'))==='15,75 m²');
check('already decorated server area remains consistent',area(render('15,75 m²','3,5 × 1,5 m × 3 ks.'))==='15,75 m²');
check('multiple cuts summed with quantities',area(render('4,3','1.3x0.7mx2 ks., 2.5x1mx1 ks.'))==='4,32 m²');
check('small areas retain six decimals',area(render('0,047','0.125x0.125mx3 ks.'))==='0,046875 m²');
check('floating point tails are removed',area(render('0,1','0.1x0.2mx3 ks.'))==='0,06 m²');
check('legacy area without cuts preserved',area(render('15.75',''))==='15,75 m²');
const props=render('15,8','3,5 × 1,5 m × 3 ks.');
check('dimension labels and units retained',props.find(p=>p.CODE==='HEIGHT').VALUE==='3,5 m'&&props.find(p=>p.CODE==='WIDTH').VALUE==='1,5 m');
console.log(passed,'checks passed; no browser or network access.');
